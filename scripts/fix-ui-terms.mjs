function apply(body, pairs) {
  let out = body;
  for (const [from, to] of pairs) out = out.split(from).join(to);
  return out;
}

function fixApostropheCalls(body) {
  return body
    .replace(/\$\{link\(([^,]+),\s*'([^']*(?:\\'[^']*)*)'\)\}/g, (m, p, label) => {
      const u = label.replace(/\\'/g, "'");
      if (u.includes("'")) return `\${link(${p}, "${u.replace(/"/g, '\\"')}")}`;
      return m;
    })
    .replace(/\$\{screenshot\(([^,]+),\s*'([^']*(?:\\'[^']*)*)'\)\}/g, (m, p, label) => {
      const u = label.replace(/\\'/g, "'");
      if (u.includes("'")) return `\${screenshot(${p}, "${u.replace(/"/g, '\\"')}")}`;
      return m;
    });
}

for (const locale of ['ar', 'fr']) {
  const pairs = locale === 'ar' ? AR : FR;
  for (const slug of SLUGS) {
    const file = path.join(base, locale, `${slug}.json`);
    const topic = JSON.parse(fs.readFileSync(file, 'utf8'));
    topic.body = apply(topic.body, pairs);
    if (locale === 'fr') topic.body = fixApostropheCalls(topic.body);
    fs.writeFileSync(file, JSON.stringify(topic, null, 2));
  }
  console.log('ui terms fixed', locale);
}
